import { alterCmds, columnConstraints, typeInfo } from '../../../src/parser/ast.js';
import { ident, volatileFunction } from '../../../src/rules-support.js';
import type { Rule, RuleResult } from '../../../src/types.js';

export const rule: Rule = {
  id: 'PG005',
  name: 'add-column-rewrites-table',
  severity: 'error',
  defaultOn: true,
  check(stmt, ctx) {
    if (stmt.kind !== 'AlterTableStmt') return;
    const s = stmt.inner;
    if (ctx.isNewTable(s.relation)) return;
    const table = ctx.tableName(s.relation);
    const results: RuleResult[] = [];
    for (const cmd of alterCmds(s)) {
      if (cmd.subtype !== 'AT_AddColumn') continue;
      const col = cmd.def?.ColumnDef;
      if (!col) continue;
      const name = ident(col.colname);
      const type = typeInfo(col.typeName)?.display ?? 'type';
      let cause: string | undefined;
      let fixSteps: string | undefined;
      for (const c of columnConstraints(col)) {
        if (c.contype === 'CONSTR_DEFAULT') {
          const fn = volatileFunction(c.raw_expr);
          if (fn) {
            cause = `\`DEFAULT ${fn === 'subquery' ? '(subquery)' : `${fn}()`}\` is volatile, so every existing row gets its own value and the table is rewritten`;
            fixSteps =
              `ALTER TABLE ${table} ADD COLUMN ${name} ${type};\n` +
              `ALTER TABLE ${table} ALTER COLUMN ${name} SET DEFAULT ${fn === 'subquery' ? '...' : `${fn}()`};  -- new rows only, no rewrite\n` +
              `-- backfill the existing rows in batches, each in its own transaction;\n` +
              `-- then, if the column must be NOT NULL, the validated-CHECK path (PG007)`;
          }
        } else if (c.contype === 'CONSTR_GENERATED' && c.generated_kind === 's') {
          cause = 'a `GENERATED ... STORED` column is computed for every existing row, which rewrites the table';
          fixSteps = `ALTER TABLE ${table} ADD COLUMN ${name} ${type};\n-- backfill the computed value in batches with UPDATE; keep it current with a trigger or compute it in the application`;
        } else if (c.contype === 'CONSTR_IDENTITY') {
          cause = 'an identity column assigns a sequence value to every existing row, which rewrites the table';
          fixSteps = `ALTER TABLE ${table} ADD COLUMN ${name} ${type};\n-- backfill from a sequence in batches, then ALTER COLUMN ... ADD GENERATED BY DEFAULT AS IDENTITY in a later release`;
        }
      }
      if (!cause) continue;
      results.push({
        message:
          `\`ADD COLUMN ${name}\` rewrites every row of \`${table}\` and rebuilds all its indexes under \`ACCESS EXCLUSIVE\` (\`pg_relation_filenode\` changes): ${cause}. ` +
          `Add the column nullable, set the default separately so only new rows get it, and backfill the existing rows in batches. ` +
          `Not needed if \`${table}\` is new in this release or empty.`,
        table,
        key: name,
        line: stmt.lineAt(col.location ?? 0),
        fix: fixSteps ? { kind: 'block', text: fixSteps } : undefined,
      });
    }
    return results;
  },
};
