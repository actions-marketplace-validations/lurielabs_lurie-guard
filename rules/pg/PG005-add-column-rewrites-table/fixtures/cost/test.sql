CREATE EXTENSION dblink;
-- A second session with a short lock_timeout: what the application sees.
CREATE FUNCTION app_conn() RETURNS text LANGUAGE sql AS $$
  SELECT 'dbname=' || current_database() || ' options=''-c lock_timeout=200''';
$$;

-- PG005: a volatile default, a stored generated column and an identity column
-- rewrite the table (new relfilenode) and its indexes.
CREATE SEQUENCE orders_seq;
CREATE SCHEMA app;
CREATE FUNCTION app.make_token() RETURNS text LANGUAGE sql VOLATILE AS $$ SELECT md5(random()::text) $$;
ALTER TABLE orders DROP COLUMN created_at;  -- the shared setup has one; the fixture adds it
SELECT pg_relation_filenode('orders') AS node, pg_relation_filenode('orders_pkey') AS pkey_node \gset
ALTER TABLE orders ADD COLUMN created_at timestamptz NOT NULL DEFAULT clock_timestamp();
SELECT assert_true(pg_relation_filenode('orders') <> :node, 'volatile default rewrote the table');
SELECT assert_true(pg_relation_filenode('orders_pkey') <> :pkey_node, 'and rebuilt the primary key index');
SELECT pg_relation_filenode('orders') AS node \gset
ALTER TABLE orders ADD COLUMN public_id uuid NOT NULL DEFAULT gen_random_uuid();
SELECT assert_true(pg_relation_filenode('orders') <> :node, 'gen_random_uuid() default rewrote the table');
SELECT pg_relation_filenode('orders') AS node \gset
ALTER TABLE orders ADD COLUMN seq bigint DEFAULT nextval('orders_seq');
SELECT assert_true(pg_relation_filenode('orders') <> :node, 'nextval() default rewrote the table');
SELECT pg_relation_filenode('orders') AS node \gset
ALTER TABLE orders ADD COLUMN token text DEFAULT app.make_token();
SELECT assert_true(pg_relation_filenode('orders') <> :node, 'a user-defined volatile function rewrote the table');
SELECT pg_relation_filenode('orders') AS node \gset
ALTER TABLE orders ADD COLUMN total_cents bigint GENERATED ALWAYS AS (amount * 100) STORED;
SELECT assert_true(pg_relation_filenode('orders') <> :node, 'a stored generated column rewrote the table');
ALTER TABLE orders DROP COLUMN seq;
SELECT pg_relation_filenode('orders') AS node \gset
ALTER TABLE orders ADD COLUMN seq bigint GENERATED BY DEFAULT AS IDENTITY;
SELECT assert_true(pg_relation_filenode('orders') <> :node, 'an identity column rewrote the table');
-- The good form: a constant default keeps the filenode.
SELECT pg_relation_filenode('orders') AS node \gset
ALTER TABLE orders ADD COLUMN status text NOT NULL DEFAULT 'new';
SELECT assert_true(pg_relation_filenode('orders') = :node, 'constant default: table not rewritten');
