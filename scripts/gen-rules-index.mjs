// Generates src/generated/rules-index.ts from rules/<pack>/<ID>-<slug>/:
// the list of rule modules the engine loads (no filesystem scan at run time)
// and the catalog built from each RULE.md (frontmatter plus the help text
// that goes into SARIF and the rule pages).
//
//   node scripts/gen-rules-index.mjs          # writes the file
//   node scripts/gen-rules-index.mjs --check  # exits 1 when the file is stale
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const rulesDir = join(root, 'rules');
const out = join(root, 'src', 'generated', 'rules-index.ts');
const check = process.argv.includes('--check');

const HELP_SECTIONS = ['What it detects', 'Why it matters', 'The fix', 'When it does not apply'];

function sectionBodies(markdown) {
  const bodies = {};
  let current = null;
  for (const line of markdown.split('\n')) {
    const m = /^## (.+)$/.exec(line);
    if (m) {
      current = m[1].trim();
      bodies[current] = [];
      continue;
    }
    if (current) bodies[current].push(line);
  }
  for (const k of Object.keys(bodies)) bodies[k] = bodies[k].join('\n').trim();
  return bodies;
}

const entries = [];
if (existsSync(rulesDir)) {
  for (const pack of readdirSync(rulesDir).sort()) {
    const packDir = join(rulesDir, pack);
    for (const folder of readdirSync(packDir).sort()) {
      const ruleMd = join(packDir, folder, 'RULE.md');
      if (!existsSync(ruleMd)) continue;
      const text = readFileSync(ruleMd, 'utf8').replace(/\r\n/g, '\n');
      const fm = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
      if (!fm) throw new Error(`${ruleMd}: missing frontmatter`);
      const meta = YAML.parse(fm[1]);
      const sections = sectionBodies(fm[2]);
      const title = (/^# (.+)$/m.exec(fm[2])?.[1] ?? meta.id).trim();
      const help = HELP_SECTIONS.map((s) => `## ${s}\n\n${sections[s] ?? ''}`).join('\n\n');
      const message = (sections['Message'] ?? '').replace(/^>\s?/gm, '').trim();
      entries.push({
        id: meta.id,
        name: meta.name,
        severity: meta.severity,
        pack,
        folder: `${pack}/${folder}`,
        since: String(meta.since),
        status: meta.status ?? 'active',
        skill: meta.skill,
        evidence: meta.evidence ?? [],
        verified: String(meta.verified),
        title,
        help,
        messageTemplate: message,
      });
    }
  }
}
entries.sort((a, b) => a.id.localeCompare(b.id));

const imports = entries
  .map((e) => `import { rule as ${e.id} } from '../../rules/${e.folder}/rule.js';`)
  .join('\n');
const list = entries.map((e) => `  ${e.id},`).join('\n');
const catalog = JSON.stringify(entries, null, 2);

const content = `// Generated by scripts/gen-rules-index.mjs from rules/*/*/RULE.md. Do not edit.
import type { Rule, RuleCatalogEntry } from '../types.js';
${imports}

export const rules: Rule[] = [
${list}
];

export const catalog: RuleCatalogEntry[] = ${catalog};
`;

// The vendored skill text the explainer sends as cached context (vendor/db-skills).
const vendorDir = join(root, 'vendor', 'db-skills', 'skills');
const skills = {};
if (existsSync(vendorDir)) {
  for (const name of readdirSync(vendorDir).sort()) {
    const p = join(vendorDir, name, 'SKILL.md');
    if (existsSync(p)) skills[`db-skills/skills/${name}`] = readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
  }
}
const vendorRef = existsSync(join(root, 'vendor', 'db-skills', 'REF')) ? readFileSync(join(root, 'vendor', 'db-skills', 'REF'), 'utf8').trim() : '';
const skillsOut = join(root, 'src', 'generated', 'skills.ts');
const skillsContent = `// Generated by scripts/gen-rules-index.mjs from vendor/db-skills. Do not edit.
export const SKILLS_REF = ${JSON.stringify(vendorRef)};
export const skillText: Record<string, string> = ${JSON.stringify(skills, null, 2)};
`;

if (check) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  const currentSkills = existsSync(skillsOut) ? readFileSync(skillsOut, 'utf8') : '';
  if (current !== content || currentSkills !== skillsContent) {
    console.error(`${out} or ${skillsOut} is stale; run: npm run gen:rules`);
    process.exit(1);
  }
  console.log('rules index up to date');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, content);
  writeFileSync(skillsOut, skillsContent);
  console.log(`wrote ${out} (${entries.length} rules) and ${skillsOut} (${Object.keys(skills).length} skills)`);
}
